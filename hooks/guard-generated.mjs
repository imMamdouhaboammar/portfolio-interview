#!/usr/bin/env node
// PreToolUse hook. Blocks direct edits to pages that build.mjs generated.
//
// build.mjs writes .portfolio-build.json at the root of every output folder.
// A Write or Edit aimed anywhere inside such a folder is denied with a reason
// that points Claude back to profile.json, because the next build would
// silently discard a hand edit. Files outside a generated site pass through.

import { existsSync, readFileSync } from 'node:fs';
import { dirname, resolve, relative, join } from 'node:path';
import { readTarget } from './read-input.mjs';

const target = await readTarget();
if (!target) process.exit(0);

const file = resolve(target.input.cwd || process.cwd(), target.file);
let dir = dirname(file);
let siteRoot = null;
for (let i = 0; i < 6; i++) {
  if (existsSync(join(dir, '.portfolio-build.json'))) { siteRoot = dir; break; }
  const up = dirname(dir);
  if (up === dir) break;
  dir = up;
}
if (!siteRoot) process.exit(0);

let profile = 'profile.json';
try {
  const rec = JSON.parse(readFileSync(join(siteRoot, '.portfolio-build.json'), 'utf8'));
  if (rec.profile) profile = rec.profile;
} catch { /* older build record without the profile path */ }

const reason = [
  `${relative(target.input.cwd || process.cwd(), file) || file} is generated by the portfolio-interview build and gets overwritten on the next build.`,
  `Make the change in ${profile} instead, then rebuild with scripts/build.mjs and rerun scripts/check.mjs.`,
  'Design changes belong in the skill template (assets/template/site.css), not in the output folder.',
].join(' ');

process.stdout.write(JSON.stringify({
  hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'deny', permissionDecisionReason: reason },
}));
process.exit(0);
